import { test, expect } from "@playwright/test";
import { mock } from "../test-support/mock-supabase.js";
import { supportStore } from "../test-support/support-store.js";
import { sharedWorkspaceApi } from "../test-support/shared-route.js";
import { supportApi } from "../test-support/support-route.js";

test("anonymous laptop and phone share members, progression, catalogue and equipment while private sections stay gated", async ({ browser }) => {
  const record = { revision: 1, members: [{ id: "shared-member", name: "Public Scout" }], incidents: [] };
  const shared = sharedWorkspaceApi(supportStore(), { publicEdits: true });
  const support = supportApi(supportStore(), null, { publicEdits: true });
  const contexts = [];
  const pages = [];
  let privateReads = 0;
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    contexts.push(context);
    const page = await context.newPage();
    pages.push(page);
    await page.clock.install();
    await mock(page, []);
    await page.route("**/rest/v1/rpc/workspace_public_read_enabled", (route) => route.fulfill({ json: true }));
    await page.route("**/rest/v1/public_patrol_records**", (route) => route.fulfill({ json: [{ revision: record.revision, payload: { members: record.members, incidents: record.incidents } }] }));
    await page.route("**/rest/v1/patrol_records**", async (route) => { privateReads++; await route.fulfill({ status: 403, json: { message: "private" } }); });
    await page.route("**/rest/v1/rpc/save_public_patrol", async (route) => {
      const input = route.request().postDataJSON();
      if (input.expected_revision !== record.revision) return route.fulfill({ json: [] });
      record.members = input.public_members;
      record.incidents = input.public_incidents;
      record.revision++;
      await route.fulfill({ json: [{ revision: record.revision }] });
    });
    await page.route("**/.netlify/functions/shared-workspace*", shared);
    await page.route("**/.netlify/functions/patrol-support*", support.route);
    await page.goto("/");
    await page.getByRole("button", { name: /PATROUILLE 01/ }).click();
    await page.getByRole("button", { name: /Gérer les membres/ }).click();
    await expect(page.locator(".member-list")).toContainText("Public Scout");
    await expect(page.getByRole("button", { name: "Continue with Google", exact: true })).toHaveCount(0);
  }
  const [laptop, phone] = pages;
  await laptop.getByPlaceholder("Ex. Marc Haddad").fill("Added without an account");
  await laptop.getByRole("button", { name: "Ajouter un membre", exact: true }).click();
  await expect.poll(() => record.members.length).toBe(2);
  await phone.clock.fastForward(10500);
  await expect(phone.locator(".member-list")).toContainText("Added without an account");
  for (const page of pages) await page.locator(".modal-close").click();
  await laptop.getByRole("button", { name: "Progression", exact: true }).click();
  await laptop.getByLabel("Membre", { exact: true }).selectOption("shared-member");
  await laptop.locator(".badge-card").nth(4).click();
  await laptop.getByLabel("Ce que j’ai accompli", { exact: true }).fill("Public shared achievement");
  await laptop.getByRole("button", { name: "Ajouter une réalisation", exact: true }).click();
  await phone.getByRole("button", { name: "Progression", exact: true }).click();
  await phone.getByLabel("Membre", { exact: true }).selectOption("shared-member");
  await phone.locator(".badge-card").nth(4).click();
  await phone.clock.fastForward(10500);
  await expect(phone.locator(".entry-list")).toContainText("Public shared achievement");
  await phone.locator(".modal-close").click();
  await laptop.locator(".modal-close").click();
  await laptop.getByRole("button", { name: "Catalogue des 93 badges", exact: true }).click();
  const input = laptop.locator("textarea[name=badges]");
  const names = (await input.inputValue()).split("\n");
  names[0] = "Shared public catalogue";
  await input.fill(names.join("\n"));
  await laptop.getByRole("button", { name: "Enregistrer le catalogue", exact: true }).click();
  await expect(laptop.locator(".modal")).toHaveCount(0);
  await phone.clock.fastForward(10500);
  await expect(phone.locator(".badge-card").nth(4)).toContainText("Shared public catalogue");
  await phone.getByRole("button", { name: "Intendance", exact: true }).click();
  await expect(phone.getByRole("button", { name: "Ajouter du matériel", exact: true })).toBeVisible();
  await phone.getByRole("button", { name: "Ajouter du matériel", exact: true }).click();
  await phone.getByLabel("Nom du matériel", { exact: true }).fill("Public rope");
  await phone.getByLabel("Quantité", { exact: true }).fill("4");
  await phone.getByRole("button", { name: "Enregistrer le matériel", exact: true }).click();
  await expect(phone.locator(".equipment-card").filter({ hasText: "Public rope" })).toBeVisible();
  await laptop.getByRole("button", { name: "Intendance", exact: true }).click();
  await expect(laptop.locator(".equipment-card").filter({ hasText: "Public rope" })).toBeVisible();
  await phone.getByRole("button", { name: "Secouriste", exact: true }).click();
  await phone.getByRole("button", { name: "Incident", exact: true }).click();
  await phone.getByRole("button", { name: "Créer un rapport d’incident", exact: true }).click();
  await phone.getByLabel("Événement ou réunion", { exact: true }).fill("Public first-aid event");
  await phone.getByLabel("Description de l’incident", { exact: true }).fill("Fictional shared report for device validation.");
  await phone.getByRole("button", { name: "Enregistrer le rapport en ligne", exact: true }).click();
  await expect.poll(() => record.incidents.length).toBe(1);
  await laptop.getByRole("button", { name: "Secouriste", exact: true }).click();
  await laptop.getByRole("button", { name: "Incident", exact: true }).click();
  await laptop.clock.fastForward(10500);
  await expect(laptop.locator(".incident-card")).toContainText("Public first-aid event");
  for (const name of ["Trésorier", "Secrétariat"]) {
    await phone.getByRole("button", { name, exact: true }).click();
    await expect(phone.getByRole("heading", { name: "Accès réservé · Goélands" })).toBeVisible();
  }
  await phone.getByRole("button", { name: "Continue with Google", exact: true }).click();
  await expect(phone.getByRole("heading", { name: "Accès réservé · Goélands" })).toBeVisible();
  await expect(phone.getByText(/Cette adresse n’a pas accès/)).toBeVisible();
  expect(privateReads).toBe(0);
  for (const context of contexts) await context.close();
});
